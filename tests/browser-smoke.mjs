import assert from "node:assert/strict";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true});
const base="http://127.0.0.1:8000/";
try{
 const page=await browser.newPage({viewport:{width:1300,height:900},acceptDownloads:true});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(base,{waitUntil:"networkidle"});
 await page.locator(".hero h1").waitFor({timeout:8000});
 for(const route of ["signals","creators","contracts","home"]){
  await page.locator('.nav a[href="#/'+route+'"]').click();
  assert.equal(await page.locator("#main h1").count(),1);
 }
 await page.locator('.nav a[href="#/signals"]').click();
 await page.locator('#signalForm [name="title"]').fill("Original cultural audio communities");
 await page.locator('#signalForm [name="observation"]').fill("Creators published original releases and recurring visible collaboration events.");
 await page.locator('#signalForm [name="risk"]').fill("Observed engagement could be manipulated or short-lived.");
 await page.locator('#signalForm [name="sourceUrl"]').fill("http://example.org/research");
 await page.locator('#signalForm button[type="submit"]').click();
 assert.equal(await page.locator("[data-signal-id]").count(),0);
 await page.locator('#signalForm [name="sourceUrl"]').fill("https://example.org/creator-research");
 await page.locator('#signalForm button[type="submit"]').click();
 assert.equal(await page.locator("[data-signal-id]").count(),1);
 let state=await page.evaluate(()=>JSON.parse(localStorage.getItem("watchtower.crypto.research.v1")));
 assert.equal(state.signals.length,1);
 assert.equal(state.signals[0].evidenceStatus,"user-supplied-unverified");
 assert.equal(state.signals[0].sourceUrl,"https://example.org/creator-research");
 const download=page.waitForEvent("download");
 await page.locator('[data-action="export-signal"]').click();
 const item=await download;assert.match(item.suggestedFilename(),/watchtower-opportunity/);
 await page.reload({waitUntil:"networkidle"});
 await page.locator("[data-signal-id]").waitFor();
 await page.locator("#domainFilter").selectOption("Other");
 assert.equal(await page.locator("[data-signal-id]").count(),0);
 await page.locator("#domainFilter").selectOption("All");
 assert.equal(await page.locator("[data-signal-id]").count(),1);
 await page.locator('.nav a[href="#/creators"]').click();
 await page.locator('#creatorForm [name="handle"]').fill("@originalbuilder");
 await page.locator('#creatorForm [name="url"]').fill("https://example.org/public-profile");
 await page.locator('#creatorForm [name="note"]').fill("Research public creative claims against deliverables.");
 await page.locator('#creatorForm button[type="submit"]').click();
 assert.equal(await page.locator("[data-creator-id]").count(),1);
 await page.locator('[data-action="remove-creator"]').click();
 assert.equal(await page.locator("[data-creator-id]").count(),0);
 await page.locator('.nav a[href="#/signals"]').click();
 await page.locator('[data-action="remove-signal"]').click();
 assert.equal(await page.locator("[data-signal-id]").count(),0);
 assert.equal(await page.locator('[data-action="connect-wallet"],[data-action="mint-token"],[data-action="trade"],[data-action="submit-to-forge"]').count(),0);
 assert.equal(errors.length,0,errors.join("\n"));
 const nojs=await browser.newPage({javaScriptEnabled:false});await nojs.goto(base);
 await nojs.getByText("Research opportunity journal with original evidence and explicit risk").waitFor();
 await nojs.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto(base);
 await mobile.locator(".hero h1").waitFor({timeout:8000});
 await mobile.locator('.nav a[href="#/signals"]').click();
 await mobile.locator("#signalForm").waitFor();
 console.log("Watchtower Crypto independent research, HTTPS gate, manual creator CRUD, JSON export, filters, storage and mobile PASS");
}catch(e){console.error("Watchtower browser E2E failed:",e);process.exitCode=1;}finally{await browser.close();}
